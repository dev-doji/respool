#!/usr/bin/env node
// Builds web/data.js from the repo's real files, so no number on the page is typed by hand:
//   deployments/*.json   -> contract addresses
//   results/loops*.jsonl -> every measured loop (the observer's raw output)
// Run after new deployments or new measurement batches:  node web/build-data.mjs
import { readFileSync, writeFileSync, existsSync } from "node:fs";
import { join, dirname } from "node:path";
import { fileURLToPath } from "node:url";

const ROOT = join(dirname(fileURLToPath(import.meta.url)), "..");
const readJson = (p) => JSON.parse(readFileSync(join(ROOT, p), "utf8"));
const readJsonl = (p) =>
  existsSync(join(ROOT, p))
    ? readFileSync(join(ROOT, p), "utf8").trim().split("\n").filter(Boolean).map((l) => JSON.parse(l))
    : [];

const pct = (xs, q) => {
  const s = [...xs].sort((a, b) => a - b);
  return s.length ? s[Math.min(s.length - 1, Math.ceil((q / 100) * s.length) - 1)] : null;
};
const summarise = (xs) => ({ n: xs.length, median: pct(xs, 50), p95: pct(xs, 95), min: Math.min(...xs), max: Math.max(...xs) });

// Batches in the order they ran. `current` marks the batch run against the deployed contracts.
const BATCHES = [
  { id: "b1", label: "Batch 1", note: "first live run", files: ["results/loops.jsonl"] },
  { id: "b2", label: "Batch 2", note: "after the drain fix", files: ["results/loops-v2.jsonl"] },
  { id: "b3", label: "Batch 3", note: "volume-based demand", files: ["results/loops-v3-balanced.jsonl", "results/loops-v3-burst.jsonl"] },
  { id: "b4", label: "Batch 4", note: "swap-count demand (current)", files: ["results/loops-v4-balanced.jsonl", "results/loops-v4-burst.jsonl"], current: true },
];

const batches = BATCHES.map((b) => {
  const recs = b.files.flatMap(readJsonl);
  const re = (chain) => recs.filter((r) => r.kind === "recentre" && r.swapChain === chain).map((r) => r.fullBlockMs);
  const moves = recs.filter((r) => r.kind === "move");
  const dir = (src) => moves.filter((m) => m.srcChain === src).length;
  return {
    id: b.id, label: b.label, note: b.note, current: !!b.current,
    recentreBase: re("base").length ? summarise(re("base")) : null,
    recentreUnichain: re("unichain").length ? summarise(re("unichain")) : null,
    moves: moves.length ? summarise(moves.map((m) => m.fullBlockMs)) : null,
    movesIntoBase: dir("unichain"), movesIntoUnichain: dir("base"),
    topups: recs.filter((r) => r.kind === "topup").length,
  };
});

// Every loop from the current batch, trimmed to what the loop player needs.
const current = BATCHES.find((b) => b.current);
const loops = current.files.flatMap(readJsonl).filter((r) => r.kind === "recentre" || r.kind === "move").map((r, i) => ({
  i: i + 1, kind: r.kind, swapChain: r.swapChain, srcChain: r.srcChain ?? null,
  fullBlockMs: r.fullBlockMs, fullSeenMs: r.fullSeenMs, swapBlock: r.swapBlock,
  swapTx: r.swapTx, reactiveTx: r.reactiveTx ?? r.moveRequestedTx ?? null, callbackTx: r.callbackTx ?? null,
  departedTx: r.departedTx ?? null, arriveRequestedTx: r.arriveRequestedTx ?? null, arrivedTx: r.arrivedTx ?? null,
  toReactiveSeenMs: r.toReactiveSeenMs ?? null, toCallbackSeenMs: r.toCallbackSeenMs ?? null, legsSeenMs: r.legsSeenMs ?? null,
}));

const dep = (id) => readJson(`deployments/${id}.json`);
const lasna = dep(5318007), base = dep(84532), uni = dep(1301);

const data = {
  generatedAt: new Date().toISOString(),
  chains: {
    lasna: { id: 5318007, name: "Reactive Lasna", rpc: "https://lasna-rpc.rnk.dev/", explorer: "https://lasna.reactscan.net", brain: lasna.brain },
    base: { id: 84532, name: "Base Sepolia", rpc: "https://sepolia.base.org", explorer: "https://sepolia.basescan.org", vault: base.vault, poolId: base.poolId, poolManager: base.poolManager, token0: base.token0, token1: base.token1, stateView: "0x571291b572ed32ce6751a2cb2486ebee8defb9b4" },
    unichain: { id: 1301, name: "Unichain Sepolia", rpc: "https://sepolia.unichain.org", explorer: "https://sepolia.uniscan.xyz", vault: uni.vault, poolId: uni.poolId, poolManager: uni.poolManager, token0: uni.token0, token1: uni.token1, stateView: "0xc199f1072a74d4e905aba1a84d9a45e2546b6222" },
  },
  batches,
  loops,
};

writeFileSync(join(ROOT, "web", "data.js"), `// Generated by web/build-data.mjs from deployments/ and results/. Do not edit by hand.\nwindow.RESPOOL = ${JSON.stringify(data, null, 1)};\n`);
console.log(`web/data.js: ${loops.length} loops from ${current.label}, ${batches.length} batches`);
for (const b of batches) console.log(b.label, "recentre base", b.recentreBase?.median, "uni", b.recentreUnichain?.median, "moves", b.moves?.n ?? 0);
